// Generates src/lib/contract/abi.ts from the verified deployment artifact.
// Run: npm run gen:abi  (re-run only if contracts/deployed/LayBy.fuji.json changes)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const artifactPath = resolve(here, "../../contracts/deployed/LayBy.fuji.json");
const outPath = resolve(here, "../src/lib/contract/abi.ts");

const artifact = JSON.parse(readFileSync(artifactPath, "utf8"));
const out = `// GENERATED by scripts/gen-abi.mjs from contracts/deployed/LayBy.fuji.json. Do not edit.
// Deployment: ${artifact.address} on chain ${artifact.network?.chainId ?? 43113}, block ${artifact.deploymentBlock}.
export const LAYBY_ADDRESS = ${JSON.stringify(artifact.address)} as const;
export const LAYBY_DEPLOYMENT_BLOCK = ${artifact.deploymentBlock}n;
export const layByAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;
writeFileSync(outPath, out);
console.log(`Wrote ${outPath} (${artifact.abi.length} ABI entries)`);
